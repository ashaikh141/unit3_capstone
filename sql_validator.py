"""
SQL validation layer.

Every query generated by Claude must pass validate_sql() before it reaches the database.
Checks run in this order, each one independent:
  1. Not empty
  2. Stacking check: only ONE statement allowed (catches "SELECT 1; SELECT 2")
  3. Must start with SELECT or WITH (read-only)
  4. Blocked keywords, matched as WHOLE WORDS only (so `deleted_at` is allowed)
"""
import re

BLOCKED_KEYWORDS = [
    "DROP", "DELETE", "UPDATE", "INSERT", "ALTER", "TRUNCATE", "CREATE",
    "GRANT", "REVOKE", "MERGE", "EXEC", "EXECUTE", "CALL", "COPY", "INTO",
]

# \b = word boundary, so DELETE matches "DELETE" but not "deleted_at"
_BLOCKED_RE = re.compile(r"\b(" + "|".join(BLOCKED_KEYWORDS) + r")\b", re.IGNORECASE)


def _strip_comments(sql: str) -> str:
    sql = re.sub(r"/\*.*?\*/", " ", sql, flags=re.DOTALL)
    sql = re.sub(r"--[^\n]*", " ", sql)
    return sql


def _strip_string_literals(sql: str) -> str:
    return re.sub(r"'(?:[^']|'')*'", "''", sql)


def validate_sql(sql: str) -> dict:
    """Returns {"valid": bool, "reason": str}."""
    if not sql or not sql.strip():
        return {"valid": False, "reason": "Empty query"}

    cleaned = _strip_string_literals(_strip_comments(sql)).strip()

    statements = [s for s in cleaned.split(";") if s.strip()]
    if len(statements) != 1:
        return {"valid": False, "reason": f"Stacked query: {len(statements)} statements found, only 1 allowed"}

    statement = statements[0].strip()

    first_word = statement.split()[0].upper()
    if first_word not in ("SELECT", "WITH"):
        return {"valid": False, "reason": f"Only SELECT queries are allowed (got {first_word})"}

    match = _BLOCKED_RE.search(statement)
    if match:
        return {"valid": False, "reason": f"Blocked keyword: {match.group(1).upper()}"}

    return {"valid": True, "reason": "PASSED"}